import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.metrics import mean_absolute_error, mean_squared_error

# ── TRAIN/TEST SPLIT ──────────────────────────
# Last 30 days = test, everything before = train
split = df.index.max() - pd.Timedelta(days=30)
train = df[df.index <= split]
test  = df[df.index > split]

print(f"Train size: {len(train)} records")
print(f"Test size : {len(test)} records")

# ── RANDOM WALK FORECAST ──────────────────────
# Predict = previous value
test = test.copy()
test["predicted"] = test["demand"].shift(1)
test = test.dropna()

# ── EVALUATE ──────────────────────────────────
actual    = test["demand"].values
predicted = test["predicted"].values

mae  = mean_absolute_error(actual, predicted)
rmse = np.sqrt(mean_squared_error(actual, predicted))

print(f"\nRandom Walk Results:")
print(f"MAE  : {mae:.0f} trips")
print(f"RMSE : {rmse:.0f} trips")

# ── PLOT ──────────────────────────────────────
plt.figure(figsize=(14, 4))
plt.plot(test["demand"].values[:200],
         label="Actual",    color="black",     linewidth=1)
plt.plot(test["predicted"].values[:200],
         label="Predicted", color="steelblue", linewidth=1, linestyle="--")
plt.title("Random Walk Forecast — NYC Taxi Demand")
plt.ylabel("Number of Trips")
plt.xlabel("Time Steps")
plt.legend()
plt.tight_layout()
plt.savefig("day2_random_walk.png")
plt.show()

# ── ADD FEATURES ──────────────────────────────

# Time-based features (patterns you already spotted)
df["hour"]        = df.index.hour
df["day_of_week"] = df.index.dayofweek  # 0=Monday, 6=Sunday
df["is_weekend"]  = (df.index.dayofweek >= 5).astype(int)

# Lag features (past demand values as input)
df["lag_1"]  = df["demand"].shift(1)   # 30 mins ago
df["lag_2"]  = df["demand"].shift(2)   # 1 hour ago
df["lag_48"] = df["demand"].shift(48)  # Same time yesterday

# Rolling average (recent trend)
df["rolling_mean_8"] = df["demand"].shift(1).rolling(8).mean()

# Drop rows with missing values from lag/rolling
df = df.dropna()

df

print("Features created successfully")
print(f"Shape: {df.shape}")
print(f"\nFirst row of features:")
print(df.iloc[0])

import matplotlib.pyplot as plt

