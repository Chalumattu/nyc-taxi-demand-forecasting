from sklearn.linear_model import LinearRegression

split = df.index.max() - pd.Timedelta(days=30)
train = df[df.index <= split]
test  = df[df.index > split]

feature_cols = ["hour", "day_of_week", "is_weekend",
                "lag_1", "lag_2", "lag_48", "rolling_mean_8"]

X_train = train[feature_cols]
y_train = train["demand"]
X_test  = test[feature_cols]
y_test  = test["demand"]

print(f"Train size: {len(train)}")
print(f"Test size : {len(test)}")

# ── TRAIN MODEL ───────────────────────────────
model = LinearRegression()
model.fit(X_train, y_train)
print("\nModel trained successfully")

# ── PREDICT ───────────────────────────────────
predictions = model.predict(X_test)

# ── EVALUATE ──────────────────────────────────
mae  = mean_absolute_error(y_test, predictions)
rmse = np.sqrt(mean_squared_error(y_test, predictions))

print(f"\nLinear Regression Results:")
print(f"MAE  : {mae:.0f} trips")
print(f"RMSE : {rmse:.0f} trips")

print(f"\nRandom Walk Results (baseline):")
print(f"MAE  : 1256 trips")
print(f"RMSE : 1646 trips")

improvement_mae  = ((1256 - mae) / 1256) * 100
improvement_rmse = ((1646 - rmse) / 1646) * 100
print(f"\nImprovement over Random Walk:")
print(f"MAE  improved by: {improvement_mae:.1f}%")
print(f"RMSE improved by: {improvement_rmse:.1f}%")

# ── PLOT ──────────────────────────────────────
plt.figure(figsize=(14, 4))
plt.plot(y_test.values[:200],
         label="Actual",    color="black",     linewidth=1)
plt.plot(predictions[:200],
         label="Predicted", color="steelblue", linewidth=1, linestyle="--")
plt.title("Linear Regression Forecast — NYC Taxi Demand")
